package Javachallenge100days.Day02;

/**
 * Problem03
 */
public class Problem03 {

    public static void main(String[] args){
        // cube of a number
        // brute force approach
        for(int i = 1; i <= 10; i++){
            System.out.println(i * i * i);
        }
    }
}

// time complexity is: O(N)
// space complexity: O(1)