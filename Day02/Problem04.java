package Javachallenge100days.Day02;

/**
 * Problem04
 */
public class Problem04 {

    public static void main(String[] args){
        // print the square of each number
        // bruteforce approach
        for(int i = 1; i <= 10; i++){
            System.out.println("square of " + i + " is: " + i * i);
        }
    }
}


// time complexity: O(N)
// space complexity: O(1)