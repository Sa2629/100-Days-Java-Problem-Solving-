package Javachallenge100days.Day02;

public class Problem02 {
    public static void main(String[] args) {
        // Mathematics => Basics 
        // Sum of Natural Numbers
        // brute force solution will add optimized approach soon
        int sum = 0;
        for(int i = 1; i <= 50; i++){
            sum += i;
        } 
        System.out.println("the sum of n natural numbers from 1 to 50 is: " + sum);
    }
}


// space complexity is O(1)
// time complexity is O(1)
