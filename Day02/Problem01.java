package Javachallenge100days.Day02;

/**
 * Problem01
 */
public class Problem01 {

    public static void main(String[] args){
        // print all numbers from 0-10 using a loop
        // approach bruteforce
        for(int i = 0; i <= 10; i++){
            System.out.println(i);
        }
    }
}


// time complexity: O(N)
// space complexity: O(1)